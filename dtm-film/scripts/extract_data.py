#!/usr/bin/env python3
"""Pull the four countries used in the film out of the World Bank WDI mirror.

Usage:
  python3 -I scripts/extract_data.py /path/to/ddf--open_numbers--world_development_indicators

Reads   datapoints/ddf--datapoints--sp_dyn_cbrt_in--by--geo--time.csv  (SP.DYN.CBRT.IN)
        datapoints/ddf--datapoints--sp_dyn_cdrt_in--by--geo--time.csv  (SP.DYN.CDRT.IN)
Writes  data/wdi_cbr_cdr.csv   (tidy table, values exactly as published)
        data/data.js           (same numbers, loaded by film.html)
No values are smoothed, interpolated or rounded here.
"""
import csv, json, sys, pathlib

COUNTRIES = {"ner": "Niger", "bgd": "Bangladesh", "swe": "Sweden", "jpn": "Japan"}
FIRST, LAST = 1960, 2024

src = pathlib.Path(sys.argv[1]) / "datapoints"
out = pathlib.Path(__file__).resolve().parent.parent / "data"

def load(fname, col):
    vals = {}
    with open(src / fname, newline="") as f:
        for row in csv.DictReader(f):
            if row["geo"] in COUNTRIES and FIRST <= int(row["time"]) <= LAST:
                vals[(row["geo"], int(row["time"]))] = float(row[col])
    return vals

cbr = load("ddf--datapoints--sp_dyn_cbrt_in--by--geo--time.csv", "sp_dyn_cbrt_in")
cdr = load("ddf--datapoints--sp_dyn_cdrt_in--by--geo--time.csv", "sp_dyn_cdrt_in")

data = {}
with open(out / "wdi_cbr_cdr.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["iso3", "country", "year", "crude_birth_rate_per_1000", "crude_death_rate_per_1000",
                "natural_increase_per_1000"])
    for geo, name in COUNTRIES.items():
        rows = []
        for y in range(FIRST, LAST + 1):
            b, d = cbr[(geo, y)], cdr[(geo, y)]   # KeyError = a gap in the source; fail loudly
            w.writerow([geo.upper(), name, y, b, d, round(b - d, 3)])
            rows.append([y, b, d])
        data[geo] = {"name": name, "rows": rows}

(out / "data.js").write_text(
    "// Generated by scripts/extract_data.py from World Bank WDI (SP.DYN.CBRT.IN, SP.DYN.CDRT.IN).\n"
    "// Do not edit by hand.\nwindow.DTM_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", out / "wdi_cbr_cdr.csv", "and", out / "data.js")
