# `to` = the letter the correct answer should land on (assemble.py re-letters every key anyway).

def Q(id, set, topic, lo, skill, stem, opts, why, expl, hint, to, reasoning=None, diff="medium"):
    letters = "ABCD"
    order = [None] * 4
    order[letters.index(to)] = 0
    rest = [1, 2, 3]
    for i in range(4):
        if order[i] is None:
            order[i] = rest.pop(0)
    q = {"id": id, "set": set, "topic": topic, "lo": lo, "skill": skill, "difficulty": diff,
         "stem": stem,
         "options": {letters[i]: opts[order[i]] for i in range(4)},
         "answer": to,
         "explanation": expl,
         "whyNot": {letters[i]: why[order[i] - 1] for i in range(4) if order[i] != 0},
         "hint": hint}
    if reasoning: q["reasoning"] = reasoning
    return q

