def X(id, set, topic, lo, skill, stem, opts, rat, expl, to, reasoning=None, diff="medium"):
    letters = "ABCD"
    order = [None] * 4
    ti = letters.index(to)
    order[ti] = 0
    rest = [1, 2, 3]
    for i in range(4):
        if order[i] is None:
            order[i] = rest.pop(0)
    q = {"id": id, "set": set, "topic": topic, "lo": lo, "skill": skill, "difficulty": diff,
         "stem": stem,
         "options": {letters[i]: opts[order[i]] for i in range(4)},
         "answer": to,
         "rationales": {letters[i]: ("Correct. " if order[i] == 0 else "Incorrect. ") + rat[order[i]] for i in range(4)},
         "explanation": expl}
    if reasoning: q["reasoning"] = reasoning
    return q

